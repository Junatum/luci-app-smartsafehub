# Single outbound HTTP policy for SmartSafeHub cloud and package requests.
# --location --max-redirs 0 rejects 3xx redirects, including non-Location 3xx
# (also checked via HTTP status), before any credentials or body reach a new host.
# --disable must be the first curl argument to ignore user-supplied curlrc.
# No plaintext HTTP, proxy environment, insecure TLS or implicit curl redirects.

# ssh_http_request METHOD OUTPUT TIMEOUT URL BODY [HEADER ...]
# METHOD is GET or POST, BODY is a local path for POST and '' for GET.
ssh_http_request() {
 local method="$1" output="$2" timeout="$3" url="$4" body="$5" status
 shift 5
 case "$url" in https://*) ;; *) return 2 ;; esac
 case "$timeout" in ''|0|*[!0-9]*) return 2 ;; esac
 case "$method" in GET|POST) ;; *) return 2 ;; esac
 # Do not leave a previous successful response behind when a retry fails.
 [ "$output" = /dev/null ] || rm -f "$output"
 if [ "$method" = GET ]; then
  [ "$#" -eq 0 ] || return 2
  status="$("${SMARTSAFEHUB_HTTP_CURL_BIN:-curl}" --disable \
   --fail --silent --show-error --location --max-redirs 0 \
   --proto '=https' --proto-redir '=https' --noproxy '*' \
   --connect-timeout "$timeout" --max-time "$timeout" \
   --output "$output" --write-out '%{http_code}' -- "$url")" || { [ "$output" = /dev/null ] || rm -f "$output"; return 1; }
 else
  [ -f "$body" ] && [ ! -L "$body" ] || return 2
  # Header strings are generated by internal scripts, never browser/RPC input.
  # Use repeated -H options without eval or word splitting.
  # The HTTP Content-Type header is standard for every JSON POST here.
  status="$("${SMARTSAFEHUB_HTTP_CURL_BIN:-curl}" --disable \
   --fail --silent --show-error --location --max-redirs 0 \
   --proto '=https' --proto-redir '=https' --noproxy '*' \
   --connect-timeout "$timeout" --max-time "$timeout" \
   --header 'Content-Type: application/json' \
   "$@" --data-binary "@$body" --output "$output" \
   --write-out '%{http_code}' -- "$url")" || { [ "$output" = /dev/null ] || rm -f "$output"; return 1; }
 fi
 case "$status" in 2??) return 0 ;; *) [ "$output" = /dev/null ] || rm -f "$output"; return 1 ;; esac
}
